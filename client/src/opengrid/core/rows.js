import { GRID_COLUMN_TYPES, gridStringOrNumberComparator } from './columns';
import { isEmptyFilterValue } from './utils';

export const TREE_ROOT_ID = '__og_root__';

export function buildRowStore(rows, getRowId) {
    const byId = new Map();
    const ids = [];
    rows.forEach((row) => {
        const id = getRowId(row);
        if (id === undefined || id === null) {
            throw new Error(
                'OpenGrid: every row needs a unique `id`. Use the `getRowId` prop to tell the grid which field to use.',
            );
        }
        if (!byId.has(id)) ids.push(id);
        byId.set(id, row);
    });
    return { byId, ids };
}

/**
 * Builds the tree used by tree data from `getTreeDataPath`. Missing parents are
 * auto-generated (like MUI X), and replaced if a real row with that path shows up
 * later in the list.
 */
export function buildTree(ids, byId, getTreeDataPath) {
    const nodes = new Map();
    const root = { id: TREE_ROOT_ID, depth: -1, parent: null, children: [] };
    nodes.set(TREE_ROOT_ID, root);
    const nodeIdByPath = new Map();

    ids.forEach((id) => {
        const path = getTreeDataPath(byId.get(id)) || [];
        let parent = root;
        for (let depth = 0; depth < path.length; depth += 1) {
            const key = path.slice(0, depth + 1).join('\u0000');
            const isLast = depth === path.length - 1;
            const existingId = nodeIdByPath.get(key);
            const existing = existingId !== undefined ? nodes.get(existingId) : null;

            if (isLast) {
                if (existing && existing.isAutoGenerated) {
                    // A real row takes over an auto-generated parent.
                    const node = { ...existing, id, isAutoGenerated: false };
                    nodes.delete(existing.id);
                    nodes.set(id, node);
                    node.children.forEach((childId) => {
                        nodes.get(childId).parent = id;
                    });
                    const siblings = parent.children;
                    siblings[siblings.indexOf(existing.id)] = id;
                    nodeIdByPath.set(key, id);
                } else {
                    const node = {
                        id,
                        depth,
                        parent: parent.id,
                        children: [],
                        groupingKey: path[depth],
                        isAutoGenerated: false,
                    };
                    nodes.set(id, node);
                    parent.children.push(id);
                    if (!existing) nodeIdByPath.set(key, id);
                }
                break;
            }

            if (!existing) {
                const autoId = `auto-generated-row-${path.slice(0, depth + 1).join('/')}`;
                const node = {
                    id: autoId,
                    depth,
                    parent: parent.id,
                    children: [],
                    groupingKey: path[depth],
                    isAutoGenerated: true,
                };
                nodes.set(autoId, node);
                parent.children.push(autoId);
                nodeIdByPath.set(key, autoId);
                parent = node;
            } else {
                parent = existing;
            }
        }
    });

    // Post-order pass to compute descendant counts.
    const countDescendants = (nodeId) => {
        const node = nodes.get(nodeId);
        let count = 0;
        node.children.forEach((childId) => {
            count += 1 + countDescendants(childId);
        });
        node.descendantCount = count;
        node.type = node.children.length > 0 ? 'group' : 'leaf';
        return count;
    };
    countDescendants(TREE_ROOT_ID);
    return { nodes, root };
}

/**
 * Compiles a filter model into a predicate `(id) => boolean`, or `null` when
 * nothing filters. `getValue(id, column)` and `getText(id, column)` abstract
 * how values are read so tree-data grouping cells can participate.
 */
export function createFilterPredicate({
    filterModel,
    columnsByField,
    quickFilterColumns,
    getValue,
    getText,
    getRow,
    apiRef,
}) {
    const items = (filterModel.items || [])
        .map((item) => {
            const column = columnsByField.get(item.field);
            if (!column || column.filterable === false) return null;
            const operator = (column.filterOperators || []).find((op) => op.value === item.operator);
            if (!operator) return null;
            if (operator.requiresFilterValue !== false && isEmptyFilterValue(item.value)) return null;
            const apply = operator.getApplyFilterFn(item, column);
            if (!apply) return null;
            return (id) => apply(getValue(id, column), getRow(id), column, apiRef);
        })
        .filter(Boolean);

    const quickValues = (filterModel.quickFilterValues || [])
        .map((value) => String(value).trim().toLowerCase())
        .filter(Boolean);
    const quickTests = quickValues.length
        ? createQuickFilterTests(quickValues, quickFilterColumns, { getValue, getText, getRow, apiRef })
        : [];

    if (items.length === 0 && quickTests.length === 0) return null;

    const itemsAnd = filterModel.logicOperator !== 'or';
    const quickAnd = filterModel.quickFilterLogicOperator !== 'or';
    return (id) => {
        if (items.length > 0) {
            const pass = itemsAnd ? items.every((test) => test(id)) : items.some((test) => test(id));
            if (!pass) return false;
        }
        if (quickTests.length > 0) {
            const matchValue = (tests) => tests.some((test) => test(id));
            return quickAnd ? quickTests.every(matchValue) : quickTests.some(matchValue);
        }
        return true;
    };
}

// Per quick-filter column set, per row object: the row's searchable text.
const haystackCaches = new WeakMap();
const SEPARATOR = '\u0000';

const isTypeDefaultQuickFilter = (column) => {
    const typeDef = GRID_COLUMN_TYPES[column.type];
    return Boolean(typeDef) && column.getApplyQuickFilterFn === typeDef.getApplyQuickFilterFn;
};

/**
 * Quick filter: a row matches a word when any searchable column contains it,
 * in its raw value or (for formatted columns) in what the user sees. All those
 * texts are joined once per row into a cached, lowercased "haystack", so each
 * keystroke costs one `includes` per row instead of one per cell. Columns with
 * a custom `getApplyQuickFilterFn` are evaluated separately.
 */
function createQuickFilterTests(quickValues, quickFilterColumns, { getValue, getText, getRow, apiRef }) {
    const haystackColumns = [];
    const customColumns = [];
    quickFilterColumns.forEach((column) => {
        if (column.getApplyQuickFilterFn === null) return;
        if (column.getApplyQuickFilterFn && !isTypeDefaultQuickFilter(column)) customColumns.push(column);
        else haystackColumns.push(column);
    });

    let cache = haystackCaches.get(quickFilterColumns);
    if (!cache) {
        cache = new WeakMap();
        haystackCaches.set(quickFilterColumns, cache);
    }
    const build = (id) =>
        haystackColumns
            .map((column) => {
                const value = getValue(id, column);
                const raw = value !== null && value !== undefined && typeof value !== 'object' ? String(value) : '';
                return column.valueFormatter ? `${raw}${SEPARATOR}${getText(id, column)}` : raw;
            })
            .join(SEPARATOR)
            .toLowerCase();
    const haystack = (id) => {
        const row = getRow(id);
        if (!row || typeof row !== 'object') return build(id);
        let text = cache.get(row);
        if (text === undefined) {
            text = build(id);
            cache.set(row, text);
        }
        return text;
    };

    return quickValues.map((query) => {
        const custom = customColumns
            .map((column) => {
                const test = column.getApplyQuickFilterFn(query, column, apiRef);
                return test ? (id) => test(getValue(id, column), getRow(id), column, apiRef) : null;
            })
            .filter(Boolean);
        return [(id) => haystack(id).includes(query), ...custom];
    });
}

/** Compiles a sort model into `(ids) => sortedIds`, or `null` if nothing sorts. */
export function createSorter({ sortModel, columnsByField, getValue, getRow, apiRef }) {
    const rules = (sortModel || [])
        .map((item) => {
            const column = columnsByField.get(item.field);
            if (!column || column.sortable === false || !item.sort) return null;
            const comparator = column.sortComparator || gridStringOrNumberComparator;
            return {
                column,
                comparator,
                direction: item.sort === 'desc' ? -1 : 1,
                needsParams: comparator.length > 2,
            };
        })
        .filter(Boolean);
    if (rules.length === 0) return null;

    return (ids) => {
        const entries = ids.map((id) => ({
            id,
            values: rules.map((rule) => getValue(id, rule.column)),
        }));
        const params = (entry, rule, value) => ({
            id: entry.id,
            field: rule.column.field,
            value,
            row: getRow(entry.id),
            api: apiRef && apiRef.current,
        });
        entries.sort((a, b) => {
            for (let i = 0; i < rules.length; i += 1) {
                const rule = rules[i];
                const result = rule.needsParams
                    ? rule.comparator(
                          a.values[i],
                          b.values[i],
                          params(a, rule, a.values[i]),
                          params(b, rule, b.values[i]),
                      )
                    : rule.comparator(a.values[i], b.values[i]);
                if (result !== 0) return result * rule.direction;
            }
            return 0;
        });
        return entries.map((entry) => entry.id);
    };
}

/**
 * Applies filtering to a tree: a node is kept when it passes the filter or when
 * one of its descendants does. Returns the kept ids and filtered descendant counts.
 */
export function filterTree(tree, predicate) {
    const kept = new Set();
    const filteredDescendantCount = new Map();
    const visit = (nodeId) => {
        const node = tree.nodes.get(nodeId);
        let count = 0;
        node.children.forEach((childId) => {
            if (visit(childId)) count += 1 + filteredDescendantCount.get(childId);
        });
        filteredDescendantCount.set(nodeId, count);
        const self = !node.isAutoGenerated && nodeId !== TREE_ROOT_ID && predicate(nodeId);
        const keep = self || count > 0;
        if (keep) kept.add(nodeId);
        return keep;
    };
    visit(TREE_ROOT_ID);
    return { kept, filteredDescendantCount };
}

/**
 * Depth-first flattening of the (filtered, sorted) tree honouring expansion.
 * `cache` memoises each node's filtered+sorted children so toggling a group
 * does not re-sort the whole tree.
 */
export function flattenTree(tree, { kept, sorter, isExpanded, cache }) {
    const result = [];
    const childrenOf = (node) => {
        if (cache && cache.has(node.id)) return cache.get(node.id);
        let children = kept ? node.children.filter((id) => kept.has(id)) : node.children;
        if (sorter) children = sorter(children);
        if (cache) cache.set(node.id, children);
        return children;
    };
    const visit = (nodeId) => {
        const node = tree.nodes.get(nodeId);
        childrenOf(node).forEach((childId) => {
            result.push(childId);
            const child = tree.nodes.get(childId);
            if (child.children.length > 0 && isExpanded(child)) visit(childId);
        });
    };
    visit(TREE_ROOT_ID);
    return result;
}

/** All descendants of a tree node (used for selection propagation). */
export function getDescendantIds(tree, nodeId) {
    const result = [];
    const stack = [...(tree.nodes.get(nodeId)?.children || [])];
    while (stack.length) {
        const id = stack.pop();
        result.push(id);
        stack.push(...tree.nodes.get(id).children);
    }
    return result;
}
